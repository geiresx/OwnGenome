// Generated separately from real Python regex engines. String case mappings
// do not describe re.IGNORECASE, notably the Python 3.9 Cyrillic relations.
static REGEX_CASE_ENDPOINTS: LazyLock<Vec<u32>> = LazyLock::new(|| {
    let mut points: Vec<u32> = REGEX_CASE_RELATIONS
        .iter()
        .flat_map(|&(a, b)| [a, b])
        .collect();
    // Close over the engine's fold classes too. Older Python-only relations
    // already contribute both endpoints through the generated pair table.
    let class = format!(
        "[{}]",
        points
            .iter()
            .map(|c| format!(r"\x{{{c:x}}}"))
            .collect::<String>()
    );
    let hir = regex_syntax::ParserBuilder::new()
        .case_insensitive(true)
        .build()
        .parse(&class)
        .expect("fixed regex case table");
    if let regex_syntax::hir::HirKind::Class(regex_syntax::hir::Class::Unicode(set)) = hir.kind() {
        for range in set.iter() {
            points.extend(u32::from(range.start())..=u32::from(range.end()));
        }
    }
    points.sort_unstable();
    points.dedup();
    points
});

pub(super) fn version_dependent(c: char) -> bool {
    if c.is_ascii() {
        return false;
    }
    let c = u32::from(c);
    let at = VERSION_DEPENDENT.partition_point(|&(_, end)| end < c);
    VERSION_DEPENDENT
        .get(at)
        .is_some_and(|&(start, _)| start <= c)
}

/// Check the closed range without walking its code points. Endpoints alone
/// cannot validate a custom class: its interior can name a guarded scalar.
pub(super) fn range_version_dependent(start: char, end: char) -> bool {
    let (start, end) = (u32::from(start), u32::from(end));
    let at = VERSION_DEPENDENT.partition_point(|&(_, last)| last < start);
    VERSION_DEPENDENT
        .get(at)
        .is_some_and(|&(first, _)| first <= end)
}

/// Only named literals and class ranges under active IGNORECASE use this
/// relation guard. Categories and dot do not name a member of a fold class.
pub(super) fn range_regex_case_dependent(start: char, end: char) -> bool {
    let (start, end) = (u32::from(start), u32::from(end));
    REGEX_CASE_ENDPOINTS
        .get(REGEX_CASE_ENDPOINTS.partition_point(|&c| c < start))
        .is_some_and(|&c| c <= end)
}

fn validate_unicode(text: &str, file: &str, mode: Lines) -> Result<(), String> {
    for (line, text) in lines(text, mode).enumerate() {
        if text.chars().any(version_dependent) {
            return Err(format!(
                "{}:{}: Unicode version-dependent text",
                file.escape_debug(),
                line + 1
            ));
        }
    }
    Ok(())
}

